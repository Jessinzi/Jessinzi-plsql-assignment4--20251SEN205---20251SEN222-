CREATE TABLE departments (
  dept_id    INT GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  dept_name  VARCHAR2(60) NOT NULL,
  location   VARCHAR2(60),
  CONSTRAINT uq_dept_name UNIQUE (dept_name)
);
 
CREATE TABLE doctors (
  doc_id            INT GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  doc_name          VARCHAR2(50)  NOT NULL,
  specialty         VARCHAR2(60)  NOT NULL,
  dept_id           INT           NOT NULL,
  consultation_fee  NUMBER(10,2)  DEFAULT 0 NOT NULL,
  CONSTRAINT fk_doc_dept FOREIGN KEY (dept_id) REFERENCES departments(dept_id),
  CONSTRAINT ck_doc_fee  CHECK (consultation_fee >= 0)
);
 
CREATE TABLE patients (
  patient_id     INT GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  patient_name   VARCHAR2(50) NOT NULL,
  date_of_birth  DATE         NOT NULL,
  phone          VARCHAR2(20),
  CONSTRAINT uq_pat_phone UNIQUE (phone)
);
 
CREATE TABLE appointments (
  appointment_id  INT GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  patient_id      INT           NOT NULL,
  doc_id          INT           NOT NULL,
  appt_date       DATE          NOT NULL,
  diagnosis       VARCHAR2(300),
  status          VARCHAR2(10)  DEFAULT 'SCHEDULED' NOT NULL,
  CONSTRAINT fk_appt_patient FOREIGN KEY (patient_id) REFERENCES patients(patient_id),
  CONSTRAINT fk_appt_doc     FOREIGN KEY (doc_id)     REFERENCES doctors(doc_id),
  CONSTRAINT ck_appt_status  CHECK (status IN ('SCHEDULED','COMPLETED','CANCELLED')),
  CONSTRAINT uq_doc_slot     UNIQUE (doc_id, appt_date)   -- no double-booking
);
 
CREATE TABLE medications (
  med_id     INT GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  med_name   VARCHAR2(80)  NOT NULL,
  med_cost   NUMBER(10,2)  NOT NULL,
  stock_qty  NUMBER(8)     DEFAULT 0 NOT NULL,
  CONSTRAINT uq_med_name  UNIQUE (med_name),
  CONSTRAINT ck_med_cost  CHECK (med_cost >= 0),
  CONSTRAINT ck_med_stock CHECK (stock_qty >= 0)
);
 
CREATE TABLE prescriptions (
  prescription_id  INT GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  appointment_id   INT           NOT NULL,
  med_id           INT           NOT NULL,
  dosage           VARCHAR2(100) NOT NULL,
  quantity         NUMBER(6)     NOT NULL,
  CONSTRAINT fk_presc_appt FOREIGN KEY (appointment_id) REFERENCES appointments(appointment_id),
  CONSTRAINT fk_presc_med  FOREIGN KEY (med_id)         REFERENCES medications(med_id),
  CONSTRAINT ck_presc_qty  CHECK (quantity > 0)
);
 